using System.Text;

namespace Crater.Core;

public static class Links
{
	const string Header = "-- Generated by crater. Do not edit.\n";

	public static string NormalizeRelative(string path)
	{
		string result = path.Trim().Replace('\\', '/');

		while (result.StartsWith("./"))
		{
			result = result[2..];
		}

		return result.Trim('/');
	}

	public static List<string> MainSegments(string pathToMain)
	{
		string path = NormalizeRelative(pathToMain);

		if (path.Length == 0)
		{
			return [];
		}

		List<string> segments = path.Split('/', StringSplitOptions.RemoveEmptyEntries).ToList();
		string last = StripExtension(segments[^1]);

		if (last.Equals("init", StringComparison.OrdinalIgnoreCase))
		{
			segments.RemoveAt(segments.Count - 1);
		}
		else
		{
			segments[^1] = last;
		}

		return segments;
	}

	public static string TopLevel(ResolvedPackage package, string style, IReadOnlyList<TypeExport> types)
	{
		string target = style == "string"
			? $"\"./{Layout.IndexFolder}/{StringPath(package)}\""
			: $"script.Parent.{Layout.IndexFolder}{InstancePath(package)}";

		return Build(target, types);
	}

	public static string Nested(ResolvedPackage package, string style, IReadOnlyList<TypeExport> types)
	{
		string target = style == "string"
			? $"\"../{StringPath(package)}\""
			: $"script.Parent.Parent{InstancePath(package)}";

		return Build(target, types);
	}

	static string Build(string target, IReadOnlyList<TypeExport> types)
	{
		if (types.Count == 0)
		{
			return Header + $"return require({target})\n";
		}

		StringBuilder builder = new(Header);

		builder.Append($"local MODULE = require({target})\n");

		foreach (TypeExport type in types)
		{
			builder.Append($"export type {type.Name}{type.Parameters} = MODULE.{type.Name}{type.Arguments}\n");
		}

		builder.Append("return MODULE\n");

		return builder.ToString();
	}

	static string StripExtension(string name)
	{
		foreach (string extension in new[] { ".luau", ".lua" })
		{
			if (name.EndsWith(extension, StringComparison.OrdinalIgnoreCase))
			{
				return name[..^extension.Length];
			}
		}

		return name;
	}

	static IEnumerable<string> Segments(ResolvedPackage package)
	{
		return new[] { package.IndexDirectory, package.ShortName }.Concat(MainSegments(package.Manifest.PathToMain));
	}

	static string InstancePath(ResolvedPackage package)
	{
		return string.Concat(Segments(package).Select(segment => $"[\"{Escape(segment)}\"]"));
	}

	static string StringPath(ResolvedPackage package)
	{
		return string.Join('/', Segments(package));
	}

	static string Escape(string segment)
	{
		return segment.Replace("\\", "\\\\").Replace("\"", "\\\"");
	}
}
