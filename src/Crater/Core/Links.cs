using System.Text;
using System.Text.RegularExpressions;

namespace Crater.Core;

public static partial class Links
{
	const string Header = "-- Generated by crater. Do not edit.\n";

	[GeneratedRegex("^[A-Za-z_][A-Za-z0-9_]*$")]
	private static partial Regex IdentifierRegex();

	static readonly HashSet<string> LuauKeywords =
	[
		"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if",
		"in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
	];

	public static string NormalizeRelative(string path)
	{
		string result = path.Trim().Replace('\\', '/');

		while (result.StartsWith("./"))
		{
			result = result[2..];
		}

		return result.Trim('/');
	}

	public static List<string> MainSegments(string pathToMain)
	{
		string path = NormalizeRelative(pathToMain);

		if (path.Length == 0)
		{
			return [];
		}

		List<string> segments = path.Split('/', StringSplitOptions.RemoveEmptyEntries).ToList();
		string last = StripExtension(segments[^1]);

		if (last.Equals("init", StringComparison.OrdinalIgnoreCase))
		{
			segments.RemoveAt(segments.Count - 1);
		}
		else
		{
			segments[^1] = last;
		}

		return segments;
	}

	public static bool NeedsInit(PackageEntry entry)
	{
		return entry.Kind != EntryKind.Module || entry.Segments.Count > 0;
	}

	public static string PackageInit(ResolvedPackage package, string style, PackageEntry entry, IReadOnlyList<TypeExport> types)
	{
		return entry.Kind switch
		{
			EntryKind.Module => ModuleLink(Inside(style, entry.Segments), types),
			EntryKind.Collection => CollectionLink(package, style, entry),
			_ => MissingLink(package),
		};
	}

	public static string Alias(string folderName, string style, IReadOnlyList<TypeExport> types)
	{
		string target = style == "string" ? $"\"./{Escape(folderName)}\"" : $"script.Parent[\"{Escape(folderName)}\"]";

		return ModuleLink(target, types);
	}


	static string ModuleLink(string target, IReadOnlyList<TypeExport> types)
	{
		if (types.Count == 0)
		{
			return Header + $"return require({target})\n";
		}

		StringBuilder builder = new(Header);

		builder.Append($"local MODULE = require({target})\n");

		foreach (TypeExport type in types)
		{
			builder.Append($"export type {type.Name}{type.Parameters} = MODULE.{type.Name}{type.Arguments}\n");
		}

		builder.Append("return MODULE\n");

		return builder.ToString();
	}

	static string CollectionLink(ResolvedPackage package, string style, PackageEntry entry)
	{
		StringBuilder builder = new(Header);

		builder.Append("local loaders = {\n");

		foreach (CollectionMember member in entry.Members)
		{
			string target = Inside(style, [.. entry.Segments, member.Name]);

			builder.Append($"\t{Key(member.Name)} = function()\n");
			builder.Append($"\t\treturn require({target})\n");
			builder.Append("\tend,\n");
		}

		builder.Append("}\n\n");
		builder.Append("export type Modules = {\n");

		foreach (CollectionMember member in entry.Members)
		{
			string target = Inside(style, [.. entry.Segments, member.Name]);

			builder.Append($"\t{Key(member.Name)}: typeof(require({target})),\n");
		}

		builder.Append("}\n\n");
		builder.Append("local modules = setmetatable({}, {\n");
		builder.Append("\t__index = function(cache, name)\n");
		builder.Append("\t\tlocal load = loaders[name]\n\n");
		builder.Append("\t\tif load == nil then\n");
		builder.Append($"\t\t\terror(`\"{{tostring(name)}}\" is not a module of {package.Name}`, 2)\n");
		builder.Append("\t\tend\n\n");
		builder.Append("\t\tlocal value = load()\n");
		builder.Append("\t\trawset(cache, name, value)\n\n");
		builder.Append("\t\treturn value\n");
		builder.Append("\tend,\n");
		builder.Append("})\n\n");
		builder.Append("return (modules :: any) :: Modules\n");

		return builder.ToString();
	}

	static string MissingLink(ResolvedPackage package)
	{
		return Header +
			$"error(\"{package.Id} has no main module. Set path_to_main in its crater.json or add init.luau.\", 2)\n";
	}

	static string Inside(string style, IEnumerable<string> segments)
	{
		List<string> parts = segments.ToList();

		if (style == "string")
		{
			return parts.Count == 0 ? "\"@self\"" : $"\"@self/{string.Join('/', parts.Select(Escape))}\"";
		}

		return "script" + string.Concat(parts.Select(segment => $"[\"{Escape(segment)}\"]"));
	}

	static bool IsIdentifier(string name) => IdentifierRegex().IsMatch(name) && !LuauKeywords.Contains(name);

	static string Key(string name) => IsIdentifier(name) ? name : $"[\"{Escape(name)}\"]";

	static string StripExtension(string name)
	{
		foreach (string extension in new[] { ".luau", ".lua" })
		{
			if (name.EndsWith(extension, StringComparison.OrdinalIgnoreCase))
			{
				return name[..^extension.Length];
			}
		}

		return name;
	}

	static string Escape(string segment)
	{
		return segment.Replace("\\", "\\\\").Replace("\"", "\\\"");
	}
}
